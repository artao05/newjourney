/**
 * Every channel Expedition defines for a boat, as data.
 *
 * Expedition's Appendix A names each number it can compute, log, plot, alarm on or
 * show in a number box. There are 314 entries, and 361 once its numbered ranges are
 * expanded (Alternating 0-9, User 0-31, Polar 5-8 and 5%-8%). They are listed here
 * under Expedition's own names, because those names are what an Expedition user
 * types, reads in a log header and expects in a number box. Everything else is ours.
 *
 * `today` marks the channels newjourney already produces when its inputs exist.
 * The live snapshot (snapshot.ts) must produce exactly those, and a test holds the
 * two together. Flipping a flag here is how a channel is declared done.
 *
 * Source: research/raw/Expedition.txt, lines 12993-13785 (not redistributed).
 */

export const CHANNEL_GROUPS = [
  'position', 'wind', 'motion', 'environment', 'current', 'tide', 'marks', 'laylines', 'gates', 'start', 'performance', 'sails', 'fleet', 'rig', 'engine', 'user',
] as const
export type ChannelGroup = (typeof CHANNEL_GROUPS)[number]

/**
 * Units as the channel is held internally. `load` is whatever the load cell
 * reports, `latlon` is decimal degrees, and `datetime` is epoch milliseconds, UTC.
 */
export const CHANNEL_UNITS = [
  'deg', 'deg/s', 'kn', 'nm', 'm', 's', 'pct', 'degC', 'hPa', 'kPa', 'kg/m3', 'V', 'A', 'rpm', 'load', 'latlon', 'datetime',
] as const
export type ChannelUnit = (typeof CHANNEL_UNITS)[number]

/**
 * Where a value comes from. `gps`: the position fix. `instrument`: a boat sensor
 * (Signal K, NMEA, phone IMU). `computed`: derived here from other channels.
 * `forecast`: weather or tide predictions. `fleet`: other boats, AIS or radar.
 * `user`: values the sailor or a script sets.
 */
export const CHANNEL_SOURCES = ['gps', 'instrument', 'computed', 'forecast', 'fleet', 'user'] as const
export type ChannelSource = (typeof CHANNEL_SOURCES)[number]

export interface ChannelDef {
  /** Stable kebab-case id, used in layouts, logs and alarms. Never renamed. */
  id: string
  /** Expedition's name for it, exactly, spelling included ("Longtitude"). */
  name: string
  group: ChannelGroup
  unit: ChannelUnit | null
  source: ChannelSource
  /** newjourney produces it today, given its inputs. */
  today: boolean
}

function c(
  id: string,
  name: string,
  group: ChannelGroup,
  unit: ChannelUnit | null,
  source: ChannelSource,
  today = false,
): ChannelDef {
  return { id, name, group, unit, source, today }
}

